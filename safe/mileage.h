#ifndef __MILEAGE_H
#define __MILEAGE_H

#include "main.h"

/* ============================================================================
 *  mileage.h —— 里程 / A·B 点判定
 *  2026-09-29 新增。2026 电赛 H 题《车载平衡滚球运动控制系统》要用。
 *
 *  赛道(题面): A->B 直线 1.5 m, B->C 半圆 R0.5 m, C->D 直线 1.5 m,
 *              D->A 半圆 R0.5 m; 一圈 = 2x1.5 + 2x(pi*0.5) = 6.142 m。
 *    A 点处有启停线(停车点), B 点要通过并给"声光提示"。
 *
 *  ★ 只用【一个标定值】就能定出两个点: 一圈有多少编码器计数
 *    (config.h 的 MILEAGE_LAP_COUNT)。因为两点在一圈里的比例是固定的:
 *        B = 24.4% 圈,  A = 100% 圈。
 *    这样换轮子/换编码器时只要重新标一个数, 不用分别标 A、B。
 *
 *  ★ 里程 = (|左计数| + |右计数|) / 2, 从"按下启动"那一刻算起
 *    (启动时 main.c 会 Encoder_Reset())。
 *
 *  ⚠ 未标定(MILEAGE_LAP_COUNT = 0)时, 本模块【不做任何判定和提示】——
 *    这是有意的: 宁可什么都不做, 也不要拿一个假数去触发提示或停车。
 * ========================================================================== */

void Mileage_Init(void);        /* 开机调用一次 */

/* 每个控制拍调用(控制中断里, 5 ms 一拍)。它做两件事:
 *   ① 刷新当前里程;
 *   ② 跨过 B 点/A 点时, 请求一次声光提示(只记事件, 见 signal.h)。 */
void Mileage_Task(void);

int32_t Mileage_GetCount(void);     /* 车体中心已走的编码器平均计数(>=0) */

int32_t Mileage_GetLapCount(void);  /* 一圈的计数(标定值); 0 = 未标定 */

/* B 点对应的计数; <=0 表示未标定。OLED 用它显示进度。 */
int32_t Mileage_GetBPoint(void);

/* 已经通过的标记点: 0 = 还没到 B, 1 = 已过 B, 2 = 已过 A(一圈跑完)。
 * ★ 只在"跑"的时候有意义; 每次重新启动会归零。 */
uint8_t Mileage_GetMark(void);

#endif
