/* ============================================================
 *                    循 迹 参 数 总 表
 * ============================================================
 * 赛道(2026 电赛 H 题): 2 段 1.5 m 直线 + 2 个半径 0.5 m 半圆,
 *   黑线宽 1.8 cm, 周长 = 2×1.5 + 2×π×0.5 ≈ 6.14 m
 *   要求一圈 <= 20 s  ->  平均速度必须 >= 0.31 m/s
 *   标定基准: 直线段 1.5 m 要在 4.8 s 内跑完(用秒表量)
 *
 * ★★★ 最重要的一条: 探头【必须装在驱动轮轴的前方】★★★★
 *   2026-09-25 仿真结论(已含偏航静摩擦, 用本文件当前参数重扫): 探头相对
 *   驱动轮轴的前后位置是悬崖式的临界 ——
 *        探头在轮轴后 1 cm  -> 出线(偏离 6.0 cm)
 *        探头正好在轮轴上  -> 出线(偏离 6.1 cm)
 *        探头前移 0.5 cm   -> 出线(偏离 6.0 cm)
 *        探头前移 1.0 cm   -> 会丢线(横偏 49 mm, 丢线 899 拍)
 *        探头前移 2.0 cm   -> 能跑(横偏 15.8 mm, 余量很小)
 *        探头前移 3.0 cm   -> 好(横偏 8.2 mm)
 *   为什么: 只有"提前看到"才能提前打舵。探头在轮轴上时, 等它发现偏了, 车
 *   已经冲出去了 —— 表现就是"进弯反应慢, 等跑出弯道才转弯, 然后找不到线"。
 *   ★ 实测方法: 量一下【两驱动轮中心连线】到【探头板中心】的前后距离。
 *     小于 2 cm 就别调参数了, 先把它往前挪到 3~4 cm, 比改任何参数都管用。
 *   (注: 补上偏航静摩擦后, 这个悬崖从 1 cm 往后挪到了 2~3 cm —— 车更难转,
 *    对前视的要求就更高。)
 *
 * ★★★ 第二条关键原理: 车要克服"偏航静摩擦"才转得动 —— 所以打舵量必须够大
 *   纯运动学算出来的"过弯需要的差速"小得离谱:
 *       需要的差速(PWM) = (基础速度 − 电机死区) × 轮距 ÷ (2 × 圆弧半径)
 *       (死区取 8; 除以 2 是因为差速是"一侧加一侧减")
 *   H 题(轮距 0.15 m, R=0.5 m): base 32 只要 3.6 PWM。
 *   ⚠ 但这个数【只是下限, 不能用来判断"力度够不够"】: 它算的是"忽略一切
 *     摩擦时, 轮速差要多大"。真车还要先把前支撑/斜撑被横向拖动的静摩擦
 *     推开, 车才开始转 —— 仿真里把这个门槛设成 12 PWM 时, 车的行为就和
 *     实车反馈的"车头转一点、车身往外滑、整条弯贴着探头边缘"完全一致。
 *   结论: 打舵量按【静摩擦门槛】定, 不要按几何公式定。调法见 SIMPLE_KP 与
 *     下面 SIMPLE_TRIM_KI 的注释; 公式只用来估计换赛道后的相对变化。
 *
 * 【怎么调, 按顺序来】
 *   0. ★ 先确认探头的物理前视距离(见上) >= 2 cm(最好 3~4 cm)。不到就先挪探头。
 *   1. 再把 SIMPLE_BASE_SPEED 定在"能稳定沿线跑完整圈"为止。
 *      它是唯一真正决定快慢的旋钮 —— 别用 Kp 去换速度。
 *   2. 进弯迟钝 / 弯道冲出去 -> 加大 SIMPLE_LEAD_TICKS(30->40)。
 *   3. 两个弯"打舵量不一样"(如 内0外60 vs 内15外40) ->
 *      ★ 先看是不是"某个弯车偏出去了"(探头压到最外 1~2 路)。是的话就是
 *      【进弯打舵太晚】, 加大 SIMPLE_LEAD_TICKS —— 不要靠砍
 *      SIMPLE_DIFF_MAX 去"强行统一", 那会把纠偏能力一起砍掉(见上面这条的
 *      实车依据)。只有"两个弯误差都在 ±1 但差速差很多"才去查前视/限幅。
 *   4. 弯道能进、也减速了, 但转不过去(车头转、车身往外滑) ->
 *      这是【打舵量不够克服偏航静摩擦】: 加大 SIMPLE_KP(14->18->24),
 *      或加大 SIMPLE_TRIM_KI(150->220)。
 *   5. 直线压不住/持续画龙 -> 调小 SIMPLE_KP; 直道细碎抖动 -> 调小
 *      SIMPLE_LEAD_TICKS 或加大 SIMPLE_LEAD_TAU。
 *   一次只改一个参数、一次改 20~30%, 改完就试。
 * ============================================================ */

/* ---------------- A 组: 速度与打舵力度 ---------------- */
#define SIMPLE_BASE_SPEED   32    /* 基础前进速度 0~100(PWM 百分比)。
                                   * ★ 当前 32: 从 24 提上来的那一档。循迹在
                                   *   这一档稳住了再往 42 加, 每次 +4。
                                   * 仿真(含偏航静摩擦 12 PWM, 用本文件的
                                   *   Kp=14 / 上限32 / Ki=150 重扫):
                                   *     24 -> 39.4 s   弯中偏离 1.3 格
                                   *     28 -> 33.7 s   弯中偏离 1.2 格
                                   *     32 -> 25.8 s   弯中偏离 1.1 格  ★ 当前
                                   *     36 -> 22.4 s   弯中偏离 1.1 格
                                   *     42 -> 18.0 s   弯中偏离 1.2 格  <- 进 20 s
                                   *   ⚠ 这一版速度阶梯【比上一版显著变慢】:
                                   *     因为模型里补上了偏航静摩擦 —— 车要花
                                   *     力气克服它。上一版 22s/19s 那张表是在
                                   *     "没有任何偏航阻力"的模型里算的, 不可信。
                                   * 架空能转、下地不动 -> 每次 +4;
                                   * 一下地就窜/发飘     -> 每次 -4。 */
#define SIMPLE_KP           14    /* 比例: 【预测误差】每偏离【一整格】给多少 PWM。
                                   * 注意它乘的是下面"虚拟前视"算出来的预测
                                   * 误差, 不是原始误差。
                                   * ★★ 2026-09-25 从 8 回到 14, 原因是本文件
                                   *   开头那条【偏航静摩擦】:
                                   *   车要克服前支撑被横向拖动的静摩擦才转得动,
                                   *   所以"打舵量"必须够大才有任何效果。8 这一档
                                   *   在弯里只给出 4 PWM 的差速, 全被静摩擦吃掉
                                   *   —— 表现就是"车头转一点、车身照样往外走,
                                   *   整条弯都贴着探头边缘跑"。
                                   * 偏了回不来 / 过弯冲出去 -> 加大(14->18->24);
                                   * 直道来回摆               -> 调小(14->12->10)。
                                   * ★ 进弯迟钝【不要】靠加大它来治 —— 那一定
                                   *   同时把直线搞毛躁。交给虚拟前视和曲率积分。 */
#define SIMPLE_LEAD_TICKS   30    /* ★★ 虚拟前视(单位: 控制拍)。它取代了旧版的
                                   *   SIMPLE_KD 微分项, 是"进弯反应慢"的正解。
                                   *
                                   * 干什么: 传感器只看得见车正下方。这里把"误差
                                   *   正在变化的速度"低通之后往外推 N 拍, 相当于
                                   *   把探头【虚拟地往前挪】。探头装得越靠后,
                                   *   这个值就越该加大。
                                   * 等效前视距离 ≈ 拍数 × 0.005 s × 车速:
                                   *   本车 0.26 m/s 时  20 拍 ≈ 2.6 cm
                                   *                     30 拍 ≈ 3.9 cm
                                   *
                                   * ★★ 2026-09-29: 20 -> 30。实车依据是两个弯
                                   *   "打舵量不统一" ——
                                   *     弯1 内轮0 / 外轮60   (差速约 30, 顶到上限)
                                   *     弯2 内轮15 / 外轮40  (差速约 12.5)
                                   *   用输出方程反推(纯代数, 不依赖任何模型):
                                   *     `内轮 = 基础速度 - 差速`, 而基础速度又随
                                   *     差速自动收油 50%, 所以 `内轮 = 32-1.5x差速`;
                                   *     差速到 21.3 时内轮算成负数, 被"平移夹"抬到
                                   *     0, 同时外轮被推成 `2x差速` = 60。反推得
                                   *     弯1 的差速确实到了 30。
                                   *   差速要 30, 只有误差打到最外侧(±4)才凑得出
                                   *   —— 也就是【车在第一个弯先偏出去了, 控制器才
                                   *   拼命补】。仿真(含偏航静摩擦, 探头前视 3cm)
                                   *   反复验证: 上限砍到 13 能让两个弯"看起来
                                   *   统一", 代价是弯里误差从 1.0 涨到 4.0、最大
                                   *   横偏 8.5 -> 40.8 mm(探头半跨只有 20 mm, 超了
                                   *   就丢线), 摩擦假设偏大时直接出线。所以正解
                                   *   不是砍舵, 而是让车【别偏出去】。
                                   *   仿真(本文件当前参数, 只改这一项 20->30):
                                   *     最大横偏 8.5 -> 2.4 mm, 两个弯的误差都稳在
                                   *     1.0, 打舵饱和率降到 0%, 圈时 25.9 -> 26.1 s
                                   *   —— 差速不是被砍小的, 是"车不偏出去所以两个
                                   *   弯自己落到同一档"。
                                   *
                                   * ★ 为什么不能直接用 KD: 旧代码的 KD 是"本拍误差
                                   *   − 上一拍误差", 而数字探头是【一格格跳】的,
                                   *   这个差值只在那一拍(5ms)出现一次, 而电机+
                                   *   齿轮箱的机械时间常数约 30~50 ms —— 5ms 的
                                   *   指令还没等轮子转起来就没了, 等于白给。
                                   *   仿真已验证: 把 KD 从 8 加到 16、24, 在
                                   *   "探头前视不足"的场景下【一次都没救回来】;
                                   *   换成这里的低通外推立刻见效。
                                   *   低通(见 LEAD_TAU)的作用就是把这个尖峰摊成
                                   *   持续约 100 ms 的指令, 电机才跟得上。
                                   *
                                   * 还嫌进弯慢 -> 加大(30->36->40), 上限 40 ——
                                   *   仿真里 40 在传感器误判率高时会失稳出线。
                                   * 直道细碎抖动 -> 调小(30->20->12), 那是把
                                   *   传感器噪声也一起外推出去了。 */
#define SIMPLE_LEAD_TAU     20    /* 上面那个"误差变化速度"的低通时间常数(单位:
                                   * 拍)。20 拍 = 100 ms, 和电机的机械时间常数
                                   * 同量级 —— 正好把瞬时跳变摊成电机跟得上的
                                   * 持续时间。
                                   * 抖动大 -> 加大(20->30->40), 但外推会更钝、
                                   * 进弯会慢一点; 反应还不够快 -> 调小。 */
#define SIMPLE_D_LIMIT      3     /* 每拍误差跳变的限幅(单位 半格/拍)。
                                   * 数字探头遇到"黑线从最左一路跳到最右"这种
                                   * 野值时, 差分能达到 8; 不限幅会被外推成猛舵。
                                   * ★ 3 是给虚拟前视让路的: 限幅卡在 3 时, 20 拍
                                   *   外推最多给出 20×3 = 60 个半格的预测偏差,
                                   *   够用了; 卡得更小(2)就等于把前视力度砍一半。 */

#define SIMPLE_TRIM_KI      150   /* 积分速度: 千分之一 PWM / (拍 × 半格)。
                                   * 150 = 误差偏一格时每拍涨 0.15 PWM ——
                                   * 大约 0.5 秒涨够 15 PWM 的偏置。
                                   * 弯中还是贴边(余量不够)   -> 加大(150->220);
                                   * 直道开始缓慢地来回摆     -> 调小(150->100)。 */
#define SIMPLE_TRIM_LIMIT   16    /* 积分偏置的上限(PWM)。必须有上限, 否则
                                   * 万一长时间偏在一侧会积到很大、出弯后
                                   * 收不回来(积分饱和/风偏)。
                                   * 仿真: 16 最好; 给到 36 反而破坏直道。 */
#define SIMPLE_TRIM_TAU     50    /* 误差回到线上(±1 以内)之后, 积分按这个
                                   * 时间常数泄漏掉(单位: 拍, 50 拍 = 250ms)。
                                   * 它决定"出弯后多快把弯道的偏置退干净"。
                                   * ★ 仿真里 45~60 是一段稳健平台, 取中间的 50。
                                   * 出弯后车往一边偏一下 -> 调小(50->30), 退快点;
                                   * 弯中偏置总是不够     -> 调大(50->70), 留久点。 */

/* ---------------- B 组: 弯道姿态 / 丢线 ---------------- */
#define SIMPLE_DEAD_BAND    0     /* 死区(单位 半格)。★ 当前 0 = 不设死区,
                                   * 偏半格就开始修 —— 这是"别等偏出去才纠正"
                                   * 的关键。
                                   * 代价: 宽线骑在两路之间时误差会在 ±1 之间
                                   * 来回, 差速跟着抖几 PWM; 但控制周期只有
                                   * 5ms(200Hz), 电机机械上根本跟不上, 实际
                                   * 被平掉了, 肉眼看不出来。
                                   * 若真在直道上看到左右抖动 -> 改回 1。 */
#define SIMPLE_DIFF_MAX     32    /* 差速上限(单侧最大修正量, PWM)。
                                   * 这是"差速夹"—— 防止某一拍野值把舵打成猛舵。
                                   * ★ 24 -> 32: 比例项提到 14 之后, 弯里
                                   *   (预测误差 4 格) 本身就要 28 PWM, 再加
                                   *   曲率积分的偏置, 24 会把它夹住 —— 那等于
                                   *   又变回"最需要打舵的时候打不出去"。
                                   * 直道误差只有 ±1 格, 算出来最多 7 PWM, 根本
                                   * 碰不到这个上限 —— 所以放宽它不会让直道变猛,
                                   * 只放大"已经快跑丢"那一档的最大打舵量。 */
#define SIMPLE_DIFF_SLEW    3     /* ★ 差速【变化率】上限, 单位 PWM/控制拍。
                                   * 0 = 关闭(旧行为, 差速一拍就能跳到位)。
                                   *
                                   * 【为什么需要它 —— 2026-09-25 实车反馈】
                                   *   "力度是够的, 是每次左右调速时左右差速过大,
                                   *    偏离赛道了。"
                                   *   这句话点出的不是"最大舵量", 而是"舵量的
                                   *   变化速度": 误差从 +2 跳到 -2 时, 差速会从
                                   *   +14 变到 -14 —— 一拍(5ms)之内跳 28 PWM。
                                   *   电机机械时间常数 30~50ms 根本跟不上, 于是
                                   *   车得到的是一个"阶跃"指令: 先猛地一拧、车头
                                   *   甩过去, 等传感器看回来时已经转过头了, 再
                                   *   反向猛拧 —— 就这样一顿一顿地被甩出赛道。
                                   *
                                   *   加上它之后, 差速只能"爬"上去而不能"跳"上去
                                   *   (3 PWM/拍 → 从 0 到满舵约 55ms, 和电机时间
                                   *   常数同量级)。★ 关键是它【不降低任何上限】:
                                   *   持续偏一侧时照样能到达满舵, 所以不会削弱
                                   *   "克服静摩擦的力气"。
                                   *
                                   * 取值: 3 是仿真扫出来的平台(1 太慢会跑丢,
                                   *   2~6 都可用, 3 在不同摩擦假设下都不会变差)。
                                   *   还觉得"一顿一顿" -> 调小(3->2);
                                   *   进弯反应变钝了   -> 调大(3->5->8, 或 0 关闭)。 */
#define SIMPLE_CORNER_SLOW  50    /* 弯道自动收油 %: 打舵越狠, 基础速度降得越多。
                                   * ★★ 15 -> 50。15 在 base=24 时几乎等于没减速
                                   *   (|diff| 最大 16 → 只降 2.4 PWM), 提速后
                                   *   "看到弯却收不油", 等于这个保险【形同虚设】。
                                   *   50 才真正生效: 最外侧压线那一拍 base 32
                                   *   → 32-10 = 22, 差速 20 → 内侧轮只剩 2 PWM,
                                   *   效果是"边收油边大角度转"。
                                   * ★ 2026-09-25 加虚拟前视后, 这条的"结构缺陷"
                                   *   顺手被补上了: 以前收油量只看 |当前打舵|,
                                   *   进弯第一拍打舵还小、收得最少, 最需要减速的
                                   *   那一刻反而收得少; 现在打舵量里含有前视项,
                                   *   误差一开始变化就打舵, 收油也就跟着提前了。
                                   * 换小半径紧道靠它加大(50~70)。
                                   *
                                   * ★★ 2026-09-29: 单靠它【会收过头】——
                                   *   实测反馈"车跑到后面的转弯时明显减速"。
                                   *   原因: 收油量 = |diff| x 50%, 而弯道里
                                   *   diff 里含着【曲率积分】, 它在弯里顶到
                                   *   上限且不泄漏, 于是收油被叠到最大:
                                   *       直道 base 32 -> 弯道 24 -> 最深 19
                                   *   （正好撞上 CORNER_MIN 地板 19.2）。
                                   *   现在由下面的 SIMPLE_CORNER_SLOW_MAX
                                   *   兜底封顶, 本值保持 50 不用改。
                                   * 想让弯道再快一点 -> 降到 35（仿真: 圈时
                                   *   再快 0.2s, 但弯道横偏 5.2->6.6 mm, 噪声
                                   *   下 13.8->16.5 mm, 越靠近探头半跨 20 mm
                                   *   越危险, 别一次降太多）。 */
#define SIMPLE_CORNER_SLOW_MAX 6  /* ★★ 弯道收油的【绝对上限】(PWM)。
                                   * 2026-09-29 新增, 治"跑到后面的弯明显
                                   *   减速"。
                                   *
                                   * 干什么: 上面那条是"按打舵量成比例收油",
                                   *   本值给收油量封个顶 —— 不管 diff 飙到
                                   *   多少, 弯里最多只降这么多 PWM。
                                   *
                                   * 为什么必须有: |diff| 在弯里含曲率积分,
                                   *   而积分在持续弯道【顶到上限且不泄漏】,
                                   *   于是收油被叠加到最深。仿真(轮距 0.27 m):
                                   *       现状(无上限)  弯 base 24, 最深 19, 27.38 s
                                   *       加上限 6      弯 base 26, 最深 26, 25.21 s
                                   *   即"最慢的那一瞬间"从 19 提到 26 (+37%),
                                   *   圈时快 2.2 s, 而且弯道横偏反而从 8.6 mm
                                   *   降到 5.2 mm（不再被夹到地板）。
                                   *
                                   * 取值: 6 → 弯里 base 26(直道 32 的 81%)。
                                   *   · 还嫌弯里慢      -> 加大(6->8->10);
                                   *   · 弯道有偏出去/丢线 -> 调小(6->4), 或
                                   *     把上面的 CORNER_SLOW 降一档。
                                   * ⚠ 别设成 0：0 = 关闭收油, 弯道会全速冲。 */
